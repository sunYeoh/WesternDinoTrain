    // 적 스폰 및 초기화
    // ─────────────────────────────────────────────
    /// <summary>지정 각도에서 스폰 (무리 러시/보스 증원용). 생성된 Enemy 반환</summary>
    private Enemy SpawnEnemyAt(GameObject prefab, Enemy.EnemyData enemyData, int waveNum, int playerLevel, float diffL, float angleDeg)
    {
        // v6.8: 프리팹이 없으면 코드 폴백으로라도 (견습 운행·보스 증원이 조용히 비지 않게). 폴백도 꺼져 있으면 null
        if (prefab == null && !GameBalance.EnemyFallbackVisuals) return null;

        Vector3 spawnPos;
        if (GameBalance.SpawnEdgeFollowView && !tutorialSpawning)
        {
            // v6.20: 보이는 화면 밖 테두리에서 (보스 증원 등). 구 반경 12 ~ 16 은 좌우로는 화면 안이었다
            spawnPos = EdgePoint(angleDeg);
        }
        else
        {
            Vector3 center = trainTransform != null ? trainTransform.position : Vector3.zero;
            float rad = angleDeg * Mathf.Deg2Rad;
            float distance = Random.Range(spawnDistanceMin, spawnDistanceMax);
            spawnPos = new Vector3(
                center.x + Mathf.Cos(rad) * distance,
                center.y + Mathf.Sin(rad) * distance, 0f);
        }

        GameObject enemyObj = prefab != null
            ? Instantiate(prefab, spawnPos, Quaternion.identity)
            : BuildFallbackEnemy(enemyData, spawnPos);
        Enemy enemy = enemyObj.GetComponent<Enemy>();
        if (enemy != null)
        {
            enemy.data = enemyData;
            enemy.InitializeWithWaveScaling(waveNum, playerLevel, diffL);
            ApplyRouteStats(enemy);
        }
        aliveEnemyCount++;
        return enemy;
    }

    /// <summary>
    /// v6.3: 보스 패턴용 증원 스폰 ('사냥 호령' / '포효').
    /// kind: "raptor"(스팀 랩터) 또는 "ptera"(볼트 테라노돈)
    /// statMul: 증원 스탯 배율 (1보다 작으면 새끼/약체)
    /// 같은 방향에서 떼로 나타난다 (무리 연출)
    /// </summary>
    public void SpawnReinforcements(string kind, int count, float statMul)
    {
        GameObject prefab = (kind == "ptera") ? boltTeranodonPrefab : steamRaptorPrefab;
        Enemy.EnemyData ed = (kind == "ptera") ? Enemy.BoltTeranodon : Enemy.SteamRaptor;

        if (prefab == null)
        {
            Debug.LogWarning("[WaveManager] 증원 프리팹 미할당: " + kind);
            return;
        }

        int playerLevel = GameManager.Instance != null ? GameManager.Instance.playerLevel : 1;
        float baseAngle = Random.Range(0f, 360f);

        for (int i = 0; i < count; i++)
        {
            Enemy e = SpawnEnemyAt(prefab, ed, currentWaveNumber, playerLevel,
                GameBalance.EnemyDifficultyL, baseAngle + Random.Range(-30f, 30f));

            if (e != null && !Mathf.Approximately(statMul, 1f))
            {
                e.currentHP *= statMul;
                e.scaledMaxHP = e.currentHP;
                e.scaledATK *= statMul;
            }
        }

        Debug.Log("[WaveManager] 보스 증원 스폰: " + kind + " x" + count + " (배율 " + statMul + ")");
    }

    /// <summary>
    /// v6.8 견습 운행: 디렉터가 부르는 손님. kind = "raptor"(스팀 랩터) / "ptera"(독침 프테라) / "bolt"(볼트 테라노돈).
    /// 웨이브와 무관하게(isWaveActive 아님) 스폰. statMul 로 약체/정식 조절. 생성된 Enemy 목록을 돌려준다.
    /// angleDeg >= 0 이면 그 방향(±10도)에서, distance > 0 이면 그 거리(+0~1.5)에서 - 튜토리얼은 기차 꼬리 오른쪽 화면 안에서 걸어오게 한다.
    /// (기본 스폰 거리 12~16 은 세로 방향이면 화면 밖이라 손님이 보이기도 전에 포탑 사거리 20 안에서 죽는다)
    /// </summary>
    public List<Enemy> SpawnForTutorial(string kind, int count, float statMul, float angleDeg = -1f, float distance = -1f)
    {
        List<Enemy> made = new List<Enemy>();
        GameObject prefab = steamRaptorPrefab;
        Enemy.EnemyData ed = Enemy.SteamRaptor;
        if (kind == "ptera") { prefab = poisonPteraPrefab; ed = Enemy.PoisonPtera; }
        else if (kind == "bolt") { prefab = boltTeranodonPrefab; ed = Enemy.BoltTeranodon; }

        if (trainTransform == null)
        {
            GameObject trainObj = GameObject.FindGameObjectWithTag("Train");
            if (trainObj != null) trainTransform = trainObj.transform;
        }

        int playerLevel = GameManager.Instance != null ? GameManager.Instance.playerLevel : 1;
        float savedMin = spawnDistanceMin, savedMax = spawnDistanceMax;
        if (distance > 0f) { spawnDistanceMin = distance; spawnDistanceMax = distance + 1.5f; }
        tutorialSpawning = true;   // v6.20: 견습 운행의 손님은 디렉터가 정한 각도·거리 그대로 (화면 안에서 걸어오게 잡아 둔 자리)
        for (int i = 0; i < count; i++)
        {
            float ang = angleDeg >= 0f ? angleDeg + Random.Range(-10f, 10f) : Random.Range(0f, 360f);
            Enemy e = SpawnEnemyAt(prefab, ed, 1, playerLevel, GameBalance.EnemyDifficultyL, ang);
            if (e == null) continue;
            if (!Mathf.Approximately(statMul, 1f))
            {
                e.currentHP *= statMul;
                e.scaledMaxHP = e.currentHP;
                e.scaledATK *= statMul;
            }
            made.Add(e);
        }
        spawnDistanceMin = savedMin; spawnDistanceMax = savedMax;
        tutorialSpawning = false;
        Debug.Log("[WaveManager] 견습 운행 손님: " + kind + " x" + made.Count + " (배율 " + statMul + ")");
        return made;
    }

    /// <summary>v6.2: 위험 선로 등 - 이번 웨이브 적 스탯 배율 적용</summary>
    private void ApplyRouteStats(Enemy enemy)
    {
        if (activeRoute == null || Mathf.Approximately(activeRoute.statMul, 1f)) return;

        enemy.currentHP *= activeRoute.statMul;
        enemy.scaledMaxHP = enemy.currentHP;
        enemy.scaledATK *= activeRoute.statMul;
    }

    /// <summary>
    /// B-3 기관차 레버: 전속 주행이면 스폰 간격이 줄어든다 (웨이브를 당겨오는 레버).
    /// SpawnWaveCoroutine의 모든 대기가 이 값을 쓴다 - 레버를 중간에 당겨도 즉시 반영.
    /// </summary>
    private int spawnGapCounter = 0;   // v6.10: 무리 쉼 계산용 (웨이브마다 0)
    private bool tutorialSpawning = false;   // v6.20: SpawnForTutorial 이 손님을 내보내는 중 (자리 = 디렉터가 정한 각도·거리)

    /// <summary>v6.10: 스폰 간격 = 구성값 x 전속 배율 x WaveLengthMul, 그리고 WaveGroupSize 마리마다 WaveGroupGapSec 쉼 ("위협 확인 → 조리 여유 → 활약")</summary>
    private float SpawnGap(WaveConfig config)
    {
        float gap = config.spawnInterval * EngineCab.SpawnIntervalMul * Mathf.Max(0.1f, GameBalance.WaveLengthMul);
        spawnGapCounter++;
        if (GameBalance.WaveGroupSize > 0 && spawnGapCounter % GameBalance.WaveGroupSize == 0)
            gap += GameBalance.WaveGroupGapSec;
        return gap;
    }

