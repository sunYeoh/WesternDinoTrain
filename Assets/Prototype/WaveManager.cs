    /// <summary>머릿수 배율의 크기 구분: 작은 손님(스팀 랩터·사막 전갈·과부하 플라이) / 중간(강철 랩터·비행 손님 3종·오일 캑터스) / 큰 손님(큰 손님·힐러·지원형)</summary>
