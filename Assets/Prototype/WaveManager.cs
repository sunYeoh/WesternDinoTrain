        maxWave = GameBalance.FinalWave;

        if (waveConfigs == null || waveConfigs.Count == 0)
        {
            GenerateDefaultWaveConfigs(GameBalance.FinalWave);
            configsAutoGenerated = true;
        }
    }

    // ─────────────────────────────────────────────
    // 웨이브 시작 (GameManager 또는 자동 진행에서 호출)
    // ─────────────────────────────────────────────
    public void StartWave(int waveNumber)
    {
        if (isWaveActive)
        {
            Debug.LogWarning("[WaveManager] 이미 웨이브가 진행 중입니다.");
            return;
        }
        // v6.8: 견습 운행 중에는 웨이브가 없다 - 손님은 TutorialDirector 가 SpawnForTutorial 로 직접 부른다
        if (TutorialDirector.Active)
        {
            Debug.Log("[WaveManager] 견습 운행 중 - 웨이브 시작 요청 무시");
            return;
        }

        // v6.5: 런 시작 웨이브면 지역 길이(정식 8 / F3 짧은 런 3)를 다시 읽어 구성을 재생성
        if (waveNumber == 1 && configsAutoGenerated)
        {
            maxWave = GameBalance.FinalWave;
            GenerateDefaultWaveConfigs(GameBalance.FinalWave);
            cookGateDone = false;
        }

        currentWaveNumber = waveNumber;
        isWaveActive = true;
        PostWaveHold = false;   // v6.18
        aliveEnemyCount = 0;
        spawnDone = false;
        if (waveNumber <= 1) System.Array.Clear(formationLineShown, 0, formationLineShown.Length);   // v6.19: 새 운행 - 편성 이름 한 줄을 다시 보여 준다

        // 증강 '개전 포격' 참조용: 웨이브 시작 시각 기록
        AugmentManager.WaveStartTime = Time.time;

        // 증강 '출혈 배팅': 웨이브 시작마다 기차 HP -80 (데미지 +35%의 대가)
        if (AugmentManager.BloodBet)
        {
            TrainManager tm = FindFirstObjectByType<TrainManager>();
            if (tm != null)
            {
                tm.TakeDamage(80f);
                Debug.Log("[WaveManager] 출혈 배팅 발동 - 기차 HP -80");
            }
        }

        // Phase 2-3 증강 '견습 셰프 고용': 웨이브 시작 시 발견한 T1 요리를 자동으로 만들어 둔다
        // (숙련 카운트는 오르지 않는다 - 손맛은 직접 구워야 는다)
        if (AugmentManager.ApprenticeCooks > 0 && FoodStock.Instance != null)
        {
            for (int a = 0; a < AugmentManager.ApprenticeCooks; a++)
            {
                string pick = PickRandomDiscoveredT1();
                if (pick == null) break;   // 아직 발견한 요리가 없으면 견습도 손을 못 댄다
                FoodStock.Instance.Add(pick, 1);
                RecipeData pr = RecipeDatabase.Get(pick);
                if (pr != null)
                    UIManager.Instance?.ShowStatChange("[견습 셰프] " + pr.displayName + " 1개를 만들어 뒀다");
            }
        }

        // 보스 웨이브 긴급 보급 (v4.1): 초반엔 독/전기 재료 수급처가 없어
        // 디버프 요리를 못 만드는 문제 해결 - 보스전 시작 시 재료 지급
        WaveConfig bossCheck = GetWaveConfig(waveNumber);
        if (bossCheck.hasBoss && MaterialInventory.Instance != null)
        {
            MaterialInventory.Instance.Add(MaterialType.Poison, 1);
            MaterialInventory.Instance.Add(MaterialType.Meat, 1);
            Debug.Log("[WaveManager] 보스 감지 - 긴급 보급: 독 재료 + 고기 지급");
            if (waveNumber >= GameBalance.FinalWave && GameBalance.SpinoFinalCard)
                // v6.15: 최종전의 보급은 스피노가 실어 둔 것 (고백 카드 "필요한 재료는 실어 뒀다" 와 같은 사건)
                UIManager.Instance?.ShowWaveNotice("[스피노] 실어 둔 재료 - 독샘 + 고기",
                    "그릴에서 독침 육포를 구워 두고, 무방비(그로기)일 때 [F] 로 던져라");
            else
                UIManager.Instance?.ShowWaveNotice("보스 접근 중! 긴급 보급 도착!",
                    "독샘 + 고기 지급 - 그릴에서 독침 육포를 구워 두고, 보스가 무방비(그로기)일 때 [F] 로 던져라");
        }

        WaveConfig config = GetWaveConfig(waveNumber);

        // ── 프롤로그 (1회차 한정, 설계 4절): 웨이브 1 = 스피노가 안내하는 첫 무대 ──
        // 새 씬/새 상태 없이 웨이브 1을 "랩터 3마리 + 느긋한 간격"으로 재구성하고
        // 스피노 대사 체인을 곁들인다. 클리어/보상/증강 흐름은 정상 웨이브와 동일 -
        // 첫 판부터 게임의 리듬(전투 -> 정차 -> 선로)을 원형 그대로 배운다.
        if (GameBalance.PrologueEnabled && waveNumber == 1
            && PlayerPrefs.GetInt(PROLOGUE_KEY, 0) == 0)
        {
            PlayerPrefs.SetInt(PROLOGUE_KEY, 1);
            PlayerPrefs.Save();
            prologueRun = true;

            WaveConfig intro = new WaveConfig();
            intro.waveNumber = 1;
            intro.spawnInterval = 2.5f;                       // 느긋하게 - 시간 압박 없음
            intro.difficultyL = GameBalance.EnemyDifficultyL;
            intro.steamRaptorCount = 3;                       // 애피타이저 3마리
            config = intro;

            StartCoroutine(PrologueDialogue());
            Debug.Log("[WaveManager] 프롤로그 무대 - 웨이브 1을 안내 구성으로 교체");
        }

        // v6.11: 전역 물량 배율 (유저: "웨이브가 진짜로 너무 짧다 - 물량 추가"). 프롤로그 안내 웨이브는 그대로
        if (!prologueRun || waveNumber != 1)
            ApplyRouteCounts(ref config, GameBalance.WaveCountMul);

        // v6.11: 정차 조리 제한 카운터 초기화 - 달리기 시작하면 제한 없음
        CookingBridge.StopCooksUsed = 0;

        // v6.2: 분기 선로 규칙 적용 (물량 배율 / 이른 이벤트)
        activeRoute = pendingRoute;
        pendingRoute = null;
        if (activeRoute != null)
        {
            ApplyRouteCounts(ref config, activeRoute.countMul);

            if (activeRoute.earlyEvent)
            {
                KitchenEventManager kem = FindFirstObjectByType<KitchenEventManager>();
                if (kem != null) kem.ScheduleEarlyEvent();
            }

            if (activeRoute.id != "straight")
                UIManager.Instance?.ShowStatChange("[" + activeRoute.routeName + "] 규칙 적용!");
        }

        // v6: 지역 전환 연출 (배경색 + 도입 문구)
        // 지역이 바뀐 웨이브에서는 도입 문구가 우선 - 속성 예고는 생략 (문구 덮어쓰기 방지)
        bool regionChanged = ApplyRegionTransition(waveNumber);

        // v6.9: 첫 등장 카드 (지역 → 새 손님 순, 큐로 한 장씩. 시간이 멈추므로 스폰은 카드를 다 읽은 뒤 흐른다)
        QueueFirstEncounterCards(waveNumber, config);

        // v6.10: 무리 쉼 카운터 + 웨이브 3 = 범위 요리 학습 구간 (개정안 §5 W3): 화염 재료 보장 + 소개 카드 1회
        spawnGapCounter = 0;
        if (waveNumber == 3 && GameBalance.FireGuaranteeAtWave3 > 0 && MaterialInventory.Instance != null && !TutorialDirector.Active)
        {
            int have = MaterialInventory.Instance.Get(MaterialType.Fire);
            if (have < GameBalance.FireGuaranteeAtWave3)
            {
                MaterialInventory.Instance.Add(MaterialType.Fire, GameBalance.FireGuaranteeAtWave3 - have);
                UIManager.Instance?.ShowStatChange("[보급] 화염꽃 " + (GameBalance.FireGuaranteeAtWave3 - have) + "개 - 무리에는 범위 요리를 써 봐라");
            }
            if (GameBalance.FirstEncounterBriefings)
                BriefingUI.ShowOnce("recipe_fire_fire", BriefingTexts.RecipeIntro("fire+fire"));
        }

        // 웨이브 속성 예고
        if (!regionChanged)
            ShowWaveAttributeNotice(config);

        // v6.13: 협곡의 낙뢰 예약 (지역 AmbientLightningRegion 의 일반 웨이브, 프롤로그·견습 제외)
        ambientLightningDone = true; ambientLightningAt = 0f;
        if (GameBalance.AmbientLightningOn && !TutorialDirector.Active && !(prologueRun && waveNumber == 1)
            && GameBalance.RegionOf(waveNumber) == GameBalance.AmbientLightningRegion && !GameBalance.IsBossWave(waveNumber))
        {
            ambientLightningDone = false;
            ambientLightningAt = Time.time + Random.Range(GameBalance.AmbientLightningDelayMin, GameBalance.AmbientLightningDelayMax);
        }

        // v6.13: 레버 인라인 연습 (구간 4) - 이 웨이브 시작에 (첫 등장 카드를 다 읽은 뒤 디렉터가 연다)
        if (GameBalance.InlineLeverWave > 0 && waveNumber == GameBalance.InlineLeverWave && TutorialDirector.WantsInline(4))
            TutorialDirector.PlayInline(4, null);

        Debug.Log("[WaveManager] 웨이브 " + waveNumber + " 시작!");
        // 플레이테스트 픽스: 코루틴 참조 보관 - 클리어 시 남은 스폰 예약을 끊는다
        activeSpawnRoutine = StartCoroutine(SpawnWaveCoroutine(config));
    }

