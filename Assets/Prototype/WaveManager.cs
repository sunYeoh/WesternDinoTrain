    private void SpawnBoss()
    {
        if (bossPrefab == null)
        {
            Debug.LogWarning("[WaveManager] 보스 프리팹 미할당");
            return;
        }

        // v6.18: 보스는 기차의 긴 옆면 쪽에서만 온다 - 앞뒤 끝에서 오면 멈춰 서는 자리가 화면 가장자리라 싸움이 안 보였다
        Vector3 center = trainTransform != null ? trainTransform.position : Vector3.zero;
        // 북쪽(위)에서만: 남쪽에 서면 몸 아래쪽이 하단 HUD 뒤에 가려진다 (GameBalance.BossSpawnNorthOnly)
        float bossSide = (GameBalance.BossSpawnNorthOnly || Random.value < 0.5f) ? 1f : -1f;
        float bossAngleDeg = Random.Range(55f, 125f) * bossSide;
        Vector3 spawnPos;
        if (GameBalance.SpawnEdgeFollowView)
        {
            // v6.20: 보이는 화면 밖에서 (몸이 길어 테두리보다 BossSpawnExtra 더 밖). 구 반경 12 ~ 16 은 넓게 보면 화면 안이었다
            spawnPos = EdgePoint(bossAngleDeg, GameBalance.BossSpawnExtra);
        }
        else
        {
            float bossAngle = bossAngleDeg * Mathf.Deg2Rad;
            float bossDist = Random.Range(spawnDistanceMin, spawnDistanceMax);
            spawnPos = new Vector3(center.x + Mathf.Cos(bossAngle) * bossDist, center.y + Mathf.Sin(bossAngle) * bossDist, 0f);
        }
        Instantiate(bossPrefab, spawnPos, Quaternion.identity);
        aliveEnemyCount++;
        Debug.Log("[WaveManager] 보스 메카 티렉스 등장!");

        // v6.9: 보스 첫 등장 카드 (HP 바가 뜨는 순간 = 스폰. 종류는 BossEnemy.Start 와 같은 지역 규칙)
        if (GameBalance.FirstEncounterBriefings && !TutorialDirector.Active)
        {
            int region = GameBalance.RegionOf(currentWaveNumber);
            BriefingUI.ShowOnce("boss_" + region, BriefingTexts.Boss(region));
        }
    }

    // ─────────────────────────────────────────────
    // 매 프레임: 생존 적 수 체크
    // ─────────────────────────────────────────────
    private void Update()
    {
        // [치트] B키: 다음 보스 웨이브로 점프 (테스트용 - 빌드 전 debugBossJumpEnabled false)
        if (debugBossJumpEnabled && GameBalance.CheatsAllowed && !TutorialDirector.Active && Input.GetKeyDown(KeyCode.B))
        {
            JumpToNextBossWave();
            return;
        }

        // v6.10: 정차 출발 확인 - [Enter] (다른 창이 열려 있으면 그 창 몫)
        if (WaitingDepart && (Input.GetKeyDown(KeyCode.Return) || Input.GetKeyDown(KeyCode.KeypadEnter))
            && !BriefingUI.IsOpen && BriefingUI.KeyConsumedFrame != Time.frameCount
            && !PauseMenu.IsOpen && !AugmentPickUI.IsOpen && !WorkshopUI.IsOpen && !AugmentListUI.ReadingOpen
            && !CookingMinigame.IsActive && !KitchenPanel.IsOpenStatic && !SpinoBetUI.IsOpen && !MerchantUI.IsOpen && !BranchRouteUI.IsOpen)
            RequestDepart();

        if (!isWaveActive) return;

        // v6.17 (v9.17 D5): 기차가 멈추는 중(패배 연출)이거나 운행이 끝났으면 클리어 판정·낙뢰를 하지 않는다 - 멈춘 기차가 웨이브를 깨고 결과 화면 위에 증강 창을 여는 일이 없게
        if (GameManager.Instance != null && (GameManager.Instance.DefeatPending
            || GameManager.Instance.currentState == GameManager.GameState.GameOver
            || GameManager.Instance.currentState == GameManager.GameState.Victory)) return;

        // v6.13: 인라인 연습 중 - 클리어 판정·낙뢰 타이머가 쉰다 (손님은 Enemy 가, 스폰은 WaitGap 이 멈춘다)
        if (TutorialDirector.InlineFreeze)
        {
            if (!ambientLightningDone) ambientLightningAt += Time.deltaTime;
            return;
        }

        // v6.5: 프롤로그 조리 게이트 진행 중이면 그것만 본다
        if (cookGateActive)
        {
            UpdateCookGate();
            return;
        }

        // v6.13: 협곡의 낙뢰
        if (!ambientLightningDone && Time.time >= ambientLightningAt)
            StrikeAmbientLightning();

        Enemy[] remainingEnemies = FindObjectsByType<Enemy>(FindObjectsSortMode.None);

        // v6.5 (교수 피드백 A1): 스폰 예약이 남아 있으면 화면이 비어도 클리어가 아니다 (보스 스킵 방지)
        if (remainingEnemies.Length == 0 && aliveEnemyCount > 0 && spawnDone)
        {
            // v6.5 (A11): 1회차 프롤로그 - 애피타이저를 넘겼으면 직접 조리 1회를 유도하고 나서 정산
            if (prologueRun && GameBalance.PrologueCookGate && !cookGateDone)
            {
                BeginCookGate();
                return;
            }
            OnAllEnemiesDefeated();
        }
    }

    // ─────────────────────────────────────────────
    // v6.5: 프롤로그 조리 게이트 (튜토리얼 설계 §4 "조리 1회 유도" 복원, 교수 피드백 A11/C5)
    //  - 적 없음, 시간 압박 없음. 찬장 재료(고기 2)로 더블 육포를 굽고 슬롯에 넣으면 통과
    //  - Bad 판정으로 재료를 잃으면 재보급 (최대 3회). [Enter]는 언제든 건너뛰기
    //  - 이미 전투 중에 조리->투입을 해냈다면 한 줄 칭찬 뒤 바로 통과
    // ─────────────────────────────────────────────
    private void BeginCookGate()
    {
        cookGateActive = true;
        cookGateStatic = true;
        cookGateStartTime = Time.time;
        cookGateBadsSeen = CookingBridge.BadsThisRun;
        cookGateResupplies = 0;
        cookGateHintTimer = 0f;

        // 이미 해냈으면 게이트를 열 이유가 없다
        if (CookGateSatisfied())
        {
            UIManager.Instance?.ShowStatChange("\"이미 굽고 넣었군. 배울 게 없겠어.\" - 스피노");
            EndCookGate();
            return;
        }

        EnsureCookGateMaterials();
        UIManager.Instance?.ShowWaveNotice("[첫 조리] 찬장에 고기 2개가 있다",
            "그릴 앞에서 [E] - 더블 육포를 굽고, 완성되면 요리 카드를 클릭해 빈 포탑 자리([+] 이름표)에 넣어라   ([Enter] 건너뛰기)");
        UIManager.Instance?.ShowStatChange("\"애피타이저는 끝났다. 이번엔 네 손으로 한 접시 - 보여줘라.\" - 스피노");
        Debug.Log("[WaveManager] 프롤로그 조리 게이트 시작");
    }

    /// <summary>게이트 시작 이후에 조리(Good 이상)가 끝나고, 그 뒤에 슬롯 투입이 있었는가</summary>
    private bool CookGateSatisfied()
    {
        float cookAt = CookingBridge.LastGoodCookTime;
        float insertAt = TurretSlot.LastInsertTime;
        return cookAt > 0f && insertAt > cookAt;
    }

    /// <summary>찬장 재료 보장: 고기가 2개 미만이면 채워 준다 (최대 3회)</summary>
    private void EnsureCookGateMaterials()
    {
        if (MaterialInventory.Instance == null) return;
        if (cookGateResupplies >= 3) return;
        int meat = MaterialInventory.Instance.Get(MaterialType.Meat);
        if (meat >= 2) return;
        MaterialInventory.Instance.Add(MaterialType.Meat, 2 - meat);
        cookGateResupplies++;
        if (cookGateResupplies > 1)
            UIManager.Instance?.ShowStatChange("찬장에 재료가 더 있었다 - 고기 보급. 다시 해보자");
    }

    private void UpdateCookGate()
    {
        // 건너뛰기
        if (Input.GetKeyDown(KeyCode.Return) || Input.GetKeyDown(KeyCode.KeypadEnter))
        {
            UIManager.Instance?.ShowStatChange("\"급한 성격이군. 손님은 기다려 주지 않는다.\" - 스피노");
            EndCookGate();
            return;
        }

        // 통과: 게이트 시작 후 조리 성공 -> 투입
        if (CookingBridge.LastGoodCookTime > cookGateStartTime && CookGateSatisfied())
        {
            UIManager.Instance?.ShowWaveNotice("[첫 조리] 통과",
                "\"봤지? 요리가 곧 탄환이다. 이제부터 진짜 손님들이다.\" - 스피노");
            EndCookGate();
            return;
        }

        // Bad 판정으로 재료를 잃었으면 재보급
        if (CookingBridge.BadsThisRun > cookGateBadsSeen)
        {
            cookGateBadsSeen = CookingBridge.BadsThisRun;
            EnsureCookGateMaterials();
        }

        // 조리는 했는데 투입을 안 하고 있으면 12초마다 한 번 더 안내
        cookGateHintTimer -= Time.deltaTime;
        if (cookGateHintTimer <= 0f)
        {
            cookGateHintTimer = 12f;
            if (CookingBridge.LastGoodCookTime > cookGateStartTime)
                UIManager.Instance?.ShowStatChange("완성된 요리를 하단 카드에서 클릭 -> 빈 포탑 자리의 [+] 이름표 클릭 (투입)");
            else if (Time.time - cookGateStartTime > 12f)
                UIManager.Instance?.ShowStatChange("그릴은 주방 칸 왼쪽 - [E]로 조리 창을 열고 더블 육포를 고르자   ([Enter] 건너뛰기)");
        }
    }

    private void EndCookGate()
    {
        cookGateActive = false;
        cookGateDone = true;
        cookGateStatic = false;
        Debug.Log("[WaveManager] 프롤로그 조리 게이트 종료");
        OnAllEnemiesDefeated();
    }

    /// <summary>
    /// [치트] 진행 중인 웨이브를 정리하고 다음 보스 웨이브를 바로 시작한다.
    /// 보상/증강/선로 없이 건너뛰므로 순수 보스 테스트용.
    /// </summary>
    private void JumpToNextBossWave()
    {
        if (GameManager.Instance == null) return;

        // 다음 보스 웨이브 탐색
        int target = GameManager.Instance.currentWave + 1;
        while (!GameBalance.IsBossWave(target) && target < GameBalance.FinalWave)
            target++;

        // 진행 중인 스폰/자동진행 코루틴 중단 + 남은 적 제거 (보상 없이 조용히)
        StopAllCoroutines();
        Enemy[] all = FindObjectsByType<Enemy>(FindObjectsSortMode.None);
        for (int i = 0; i < all.Length; i++)
            Destroy(all[i].gameObject);

        isWaveActive = false;
        PostWaveHold = false;     // v6.18: 위 StopAllCoroutines 가 사고 대기를 끊었을 수 있다
        aliveEnemyCount = 0;
        spawnDone = false;
        cookGateActive = false;
        cookGateDone = true;      // 치트로 건너뛴 런에서는 게이트를 다시 열지 않는다
        prologueRun = false;
        cookGateStatic = false;
        pendingRoute = null;
        activeRoute = null;
        BranchRouteUI.Instance?.Cancel();   // v6.14: 고르던 갈림길·카드·카메라 원래대로
        RouteFX.ClearTone();

        // 웨이브 카운터를 보스 직전으로 두고 바로 시작
        // (currentState 직접 변경: Town 보상 지급 없이 Battle 가드만 통과)
        GameManager.Instance.currentWave = target - 1;
        GameManager.Instance.currentState = GameManager.GameState.Town;
        GameManager.Instance.OnClickNextWave();

        UIManager.Instance?.ShowWaveNotice("[치트] 보스 점프", "웨이브 " + target + " 즉시 시작!");
        Debug.Log("[WaveManager] 치트 - 보스 웨이브 " + target + "로 점프");
    }

    // ─────────────────────────────────────────────
    // 웨이브 완료 처리 (v2: 증강 선택 -> 기존 흐름 -> 자동 진행)
    // ─────────────────────────────────────────────
    private void OnAllEnemiesDefeated()
    {
        isWaveActive = false;
        aliveEnemyCount = 0;

        // 프롤로그 마무리: 스피노의 배웅 한 줄 (첫 무대 클리어)
        if (prologueRun)
        {
            prologueRun = false;
            UIManager.Instance?.ShowStatChange(
                "\"나쁘지 않았어, 신입. 진짜 손님들은 지금부터다.\" - 스피노");
        }

        // 플레이테스트 픽스: 화면의 적을 다 잡아도 스폰 코루틴에 예약이 남아 있으면
        // 선로/베팅 고르는 정비 턴에 뒤늦게 도착한 적이 기차를 물어뜯었다 (정비 턴 사망 사고).
        // 클리어 = 이번 웨이브 스폰 계약 종료.
        if (activeSpawnRoutine != null)
        {
            StopCoroutine(activeSpawnRoutine);
            activeSpawnRoutine = null;
        }

        SoundManager.Play("sfx_wave_clear");
        Debug.Log("[WaveManager] 웨이브 " + currentWaveNumber + " 모든 적 처치 완료!");

        // v6.18 (유저 10-06 "방해 이벤트가 끝나야 다음 선택지가 나오게"): 사고가 진행 중이면 수습(해결·실패)이 끝난 뒤에 이어 간다.
        //   구: 증강 창이 사고 위에 바로 열리고, 정차로 넘어가면서 사고가 벌점 없이 사라졌다. 최종전은 기다리지 않는다 (승리 연출이 먼저)
        if (GameBalance.WaitEventBeforeChoiceSec > 0f && KitchenEventManager.IsActive && currentWaveNumber < GameBalance.FinalWave)
        {
            StartCoroutine(WaitEventThenFinish());
            return;
        }
        FinishWaveClear();
    }

    /// <summary>v6.18: 웨이브는 끝났고 사고 수습을 기다리는 중 (그동안 새 사고는 시작하지 않는다 - KitchenEventManager 가 본다)</summary>
    public static bool PostWaveHold { get; private set; }

    private IEnumerator WaitEventThenFinish()
    {
        PostWaveHold = true;
        int wave = currentWaveNumber;
        UIManager.Instance?.ShowStatChange("손님은 다 보냈다 - 사고를 수습하면 다음으로 넘어간다");
        float waited = 0f;
        while (KitchenEventManager.IsActive && waited < GameBalance.WaitEventBeforeChoiceSec)
        {
            waited += Time.deltaTime;   // 일시정지 중에는 세지 않는다
            yield return null;
        }
        // 결과 배너(해결·실패)가 읽힐 틈
        if (!KitchenEventManager.IsActive)
            yield return new WaitForSeconds(Mathf.Max(0.2f, GameBalance.EventResolveHoldSec));
        PostWaveHold = false;

        // 그 사이 기차가 멈췄거나(사고 실패 피해) 다른 경로로 흐름이 넘어갔으면 여기서 끝
        GameManager gm = GameManager.Instance;
        if (gm == null || gm.currentState != GameManager.GameState.Battle || isWaveActive || wave != currentWaveNumber) yield break;
        if (TrainManager.Instance != null && !TrainManager.Instance.IsAlive) yield break;
        FinishWaveClear();
    }

    /// <summary>웨이브 클리어의 뒷부분: 선로 보상 정산 -> (최종전이면 승리) -> 재료 보장 -> 일지 -> 증강 선택</summary>
    private void FinishWaveClear()
    {

        // v6.2: 분기 선로 클리어 보상 정산. v6.14 (선로 v2): 골드·재료 대신 "증강 1회 더"(증강 선택 뒤에 이어서) + 유물 확률 (갑판 상자)
        int journalNo = -1;
        pendingExtraPickGrade = -1; pendingExtraPickSource = null;
        if (activeRoute != null)
        {
            if (activeRoute.extraPickGrade >= 0)
            {
                pendingExtraPickGrade = activeRoute.extraPickGrade;
                pendingExtraPickSource = activeRoute.routeName;
            }
            if (activeRoute.journal)
                journalNo = MetaProgress.PickUncollectedJournal();

            // 유물: 갑판 상자로 떨어진다 (기차 어딘가 - 걸어가서 회수). 폐역은 확정, 위험·안개는 확률
            if (activeRoute.relicChance > 0f && Random.value < activeRoute.relicChance)
                DeckLoot.SpawnItemCrate(
                    Random.Range(GameBalance.TrainWalkMinX + 1f, GameBalance.TrainWalkMaxX - 1f),
                    activeRoute.id == "ghost" ? "폐역 잔해에서 발견" : "[" + activeRoute.routeName + "] 길가에서 발견");
            else if (activeRoute.relicChance > 0f)
                UIManager.Instance?.ShowStatChange("[" + activeRoute.routeName + "] 이번엔 유물이 없었다");

            RouteFX.ClearTone();   // 선로 톤 걷기
            activeRoute = null;
        }

        // v6: 최종전 클리어 -> 증강 없이 바로 승리 처리
        if (currentWaveNumber >= GameBalance.FinalWave)
        {
            GameManager.Instance?.OnWaveCleared();
            return;
        }

        // 웨이브 속성에 맞는 재료 드롭 보장
        GuaranteeAttributeDrop(currentWaveNumber);

        // v6.2: 폐역에서 일지 발견 -> 전문 연출이 닫힌 뒤 증강 선택으로
        if (journalNo > 0)
        {
            MetaProgress.CollectJournal(journalNo);
            StoryTexts.ShowJournal(journalNo, delegate { OpenAugmentPick(); });
            return;
        }

        OpenAugmentPick();
    }

    // v6.14: 선로 보상 "증강 1회 더" (사냥터 은 / 위험 금) - 이번 웨이브 증강 선택 뒤에 이어서 한 번 더 연다
    private int pendingExtraPickGrade = -1;
    private string pendingExtraPickSource = null;

    /// <summary>증강 3택1을 띄우고, 선택이 끝나면 기존 흐름을 이어간다. v6.10: AugmentPickAt(wave) 가 아닌 웨이브는 선택창 없이 웨이브 효과만. v6.14: 선로 보상 증강이 있으면 이어서</summary>
    private void OpenAugmentPick()
    {
        if (AugmentPickUI.Instance != null)
        {
            if (GameBalance.AugmentPickAt(currentWaveNumber))
                AugmentPickUI.Instance.OnWaveCleared(currentWaveNumber, delegate { OpenExtraPickThenContinue(); });
            else
            {
                AugmentPickUI.Instance.ApplyPerWaveEffects();
                OpenExtraPickThenContinue();
            }
        }
        else
        {
            // 증강 UI가 씬에 없으면 기존 흐름 그대로
            AfterAugmentPick();
        }
    }

    /// <summary>v6.14: 선로 보상 증강(등급 고정)이 있으면 한 번 더 열고, 끝나면 정차 흐름(AfterAugmentPick)</summary>
    private void OpenExtraPickThenContinue()
    {
        int grade = pendingExtraPickGrade;
        string source = pendingExtraPickSource;
        pendingExtraPickGrade = -1; pendingExtraPickSource = null;
        if (grade >= 0 && AugmentPickUI.Instance != null)
        {
            AugmentPickUI.Instance.OpenExtra(currentWaveNumber, (AugmentGrade)grade, source, delegate { AfterAugmentPick(); });
            return;
        }
        AfterAugmentPick();
    }

    /// <summary>증강 선택 완료 후: GameManager 흐름 + (보스 직전 스피노) + 분기 선로 + 자동 시작</summary>
    private void AfterAugmentPick()
    {
        GameManager.Instance?.OnWaveCleared();

        if (autoProgress && currentWaveNumber < maxWave)
        {
            int nextWave = currentWaveNumber + 1;

            // Phase 2-1: 보스 직전 정차에는 도박사 스피노가 먼저 다가온다 (베팅 후 선로 선택)
            // Phase 2-3: 그 외 정차에는 등짐장수 안킬로가 확률 등장 (아이템 행상인)
            //  - 스피노와 안킬로는 같은 역에 절대 같이 서지 않는다 ("그 도마뱀 옆엔 안 앉수다")
            // v6.10: 첫 보스는 베팅 없이 (BetMinWave), 첫 정차들은 상점 없이 (MerchantMinWave) - "초반부터 우겨 넣지 말고 하나씩"
            bool finalStop = GameBalance.SpinoNoBetAtFinal && nextWave >= GameBalance.FinalWave;   // v6.15: 최종전 직전엔 판을 접는다 (고백 카드는 최종전 시작에)
            if (GameBalance.IsBossWave(nextWave) && nextWave >= GameBalance.BetMinWave && !finalStop)
                SpinoBetUI.Show(nextWave, delegate { ProceedRouteChoice(nextWave); });
            else if (nextWave >= GameBalance.MerchantMinWave && MerchantUI.ShouldAppear(nextWave))
                MerchantUI.Show(nextWave, delegate { ProceedRouteChoice(nextWave); });
            else
                ProceedRouteChoice(nextWave);
        }
    }

    /// <summary>분기 선로 선택 -> 자동 웨이브 시작 (스피노 이후의 기존 체인)</summary>
    private void ProceedRouteChoice(int nextWave)
    {
        // v6.5 (감사 2-A): 선로 선택 빈도 1/2 - 메뉴 피로 완화
        // 짝수 웨이브 앞 + 보스 직전에만 선택, 나머지는 자동 '곧은 선로'
        bool routeChoice = BranchRouteUI.Instance != null
            && nextWave >= GameBalance.RouteChoiceMinWave   // v6.10: 첫 지역은 곧은 선로 고정 (개정안 §7)
            && (nextWave % 2 == 0 || GameBalance.IsBossWave(nextWave));

        if (routeChoice)
        {
            BranchRouteUI.Instance.ShowRoutes(nextWave, delegate (RouteData route)
            {
                pendingRoute = route;
                StartCoroutine(AutoNextWaveCoroutine(nextWave));
            });
        }
        else
        {
            pendingRoute = null;   // 곧은 선로
            StartCoroutine(AutoNextWaveCoroutine(nextWave));
        }
    }

    /// <summary>v6.10: 정차에서 출발 확인을 기다리는 중인가 (DepartUI 버튼·[Enter] 가 RequestDepart 를 부른다)</summary>
    public static bool WaitingDepart { get; private set; }
    private static bool departRequested = false;

    /// <summary>v6.10: 출발 요청 (버튼/[Enter]). 기다리는 중이 아니면 무시</summary>
    public static void RequestDepart()
    {
        if (!WaitingDepart) return;
        departRequested = true;
    }

    /// <summary>정비 시간 후 다음 웨이브 시작. v6.10: DepartConfirm 이면 시간제한 없이 [Enter]/출발 버튼을 기다린다 (구 동작 = autoProgressDelay 초 뒤 자동)</summary>
    private IEnumerator AutoNextWaveCoroutine(int nextWave)
    {
        if (GameBalance.DepartConfirm)
        {
            Debug.Log("[WaveManager] 정차 - 출발 확인 대기 (웨이브 " + nextWave + ")");
            // v6.14: 선로를 골랐으면 그 길 이름으로
            if (pendingRoute != null)
                UIManager.Instance?.ShowWaveNotice("[" + pendingRoute.routeName + "]  이 길로 간다", "준비되면  [Enter] 또는 화면 아래 [출발] 버튼  -  요리·투입·[G] 정비소는 그 전에");
            else
                UIManager.Instance?.ShowWaveNotice("정차 - 준비되면 출발", "요리·투입·[G] 정비소를 마치고  [Enter] 또는 화면 아래 [출발] 버튼");
            WaitingDepart = true; departRequested = false;
            while (!departRequested && !isWaveActive) yield return null;
            WaitingDepart = false; departRequested = false;
        }
        else
        {
            Debug.Log("[WaveManager] " + autoProgressDelay + "초 후 웨이브 " + nextWave + " 자동 시작");
            UIManager.Instance?.ShowWaveNotice("정비 시간", autoProgressDelay + "초 후 웨이브 " + nextWave + " 시작!");
            yield return new WaitForSeconds(autoProgressDelay);
        }

        // 그 사이 다른 경로로 이미 웨이브가 시작됐다면 중복 시작하지 않는다
        if (isWaveActive)
        {
            Debug.Log("[WaveManager] 이미 다른 경로로 웨이브가 시작됨 - 자동 시작 스킵");
            BranchRouteUI.Instance?.Cancel();
            yield break;
        }

        // v6.14: 출발 - 카드 치우고 고른 가지로 들어간다 (세계 밀림은 ParallaxBackground 가 두상 앞이 분기점을 지나며 진행)
        BranchRouteUI.Instance?.OnDepart();

        // GameManager를 경유해야 currentWave 카운트와 Battle 상태가 같이 올라간다
        if (GameManager.Instance != null)
            GameManager.Instance.OnClickNextWave();
        else
            StartWave(nextWave);   // GameManager 없는 테스트 씬용 폴백
    }

    /// <summary>
    /// v5.2: 웨이브 종료 시 보유량이 0인 재료를 1개 보장 지급.
    /// (구 문자열 Inventory 기반 -> MaterialInventory 6종 기반으로 교체)
    /// 웨이브 구간에 따라 우선순위가 다르다:
    ///  - 초반(~10): 고기 / 화염 위주 (기초 요리 재료)
    ///  - 중반(~20): 전기 / 독 (제어 계열 해금 구간)
    ///  - 후반(21~): 냉기 / 장갑 (상위 조합 구간)
    /// 우선순위 목록에서 "보유량 0"인 첫 재료만 1개 지급하므로
    /// 파밍을 잘하는 플레이어에게는 아무것도 주지 않는다 (밸런스 유지).
    /// </summary>
    /// <summary>
    /// Phase 2-3 '견습 셰프 고용'용: 발견(도감 등록)한 T1 레시피 중 하나를 무작위로 고른다.
    /// 아무것도 발견 못 했으면 null (견습이 만들 줄 아는 요리가 없다)
    /// </summary>
    private string PickRandomDiscoveredT1()
    {
        if (FoodStock.Instance == null) return null;
        System.Collections.Generic.List<string> ids = new System.Collections.Generic.List<string>();
        foreach (RecipeData r in RecipeDatabase.All)
            if (r.tier == 1 && FoodStock.Instance.IsDiscovered(r.recipeId)) ids.Add(r.recipeId);
        return ids.Count > 0 ? ids[Random.Range(0, ids.Count)] : null;
    }

    private void GuaranteeAttributeDrop(int waveNum)
    {
        if (MaterialInventory.Instance == null) return;

        // Phase 2-2 증강 '비상 식량 창고': 웨이브 클리어마다 랜덤 재료 추가
        if (AugmentManager.ClearMatBonus > 0)
        {
            for (int b = 0; b < AugmentManager.ClearMatBonus; b++)
                MaterialInventory.Instance.Add((MaterialType)Random.Range(0, 6), 1);
            UIManager.Instance?.ShowStatChange("[비상 식량 창고] 랜덤 재료 +" + AugmentManager.ClearMatBonus);
        }

        // v6: 지역 기반 우선순위 목록 구성
        int region = GameBalance.RegionOf(waveNum);
        MaterialType[] priority;
        if (region == 1)
            priority = new MaterialType[] { MaterialType.Meat, MaterialType.Fire };
        else if (region == 2)
            priority = new MaterialType[] { MaterialType.Elec, MaterialType.Poison, MaterialType.Meat };
        else
            priority = new MaterialType[] { MaterialType.Ice, MaterialType.Armor, MaterialType.Fire };

        for (int i = 0; i < priority.Length; i++)
        {
            if (MaterialInventory.Instance.Get(priority[i]) > 0) continue;

            MaterialInventory.Instance.Add(priority[i], 1);
            Debug.Log("[WaveManager] 재료 보장 지급: " + priority[i]);
            UIManager.Instance?.ShowStatChange("보급: 부족한 재료 1개 지급!");
            return; // 한 번에 1종만 지급
        }
    }

    // ─────────────────────────────────────────────
    // 랜덤 스폰 위치 계산
    // ─────────────────────────────────────────────
    private Vector3 GetRandomSpawnPosition()
    {
        // v6.20: 구 방식 스폰(웨이브 1·작살 난입)도 보이는 화면 밖 테두리에서
        if (GameBalance.SpawnEdgeFollowView) return EdgePoint(Random.Range(0f, 360f));
        Vector3 center = trainTransform != null ? trainTransform.position : Vector3.zero;
        float angle = Random.Range(0f, 360f) * Mathf.Deg2Rad;
        float distance = Random.Range(spawnDistanceMin, spawnDistanceMax);

        float x = center.x + Mathf.Cos(angle) * distance;
        float y = center.y + Mathf.Sin(angle) * distance;

        return new Vector3(x, y, 0f);
    }

    // ─────────────────────────────────────────────
    // 웨이브 구성 조회
    // ─────────────────────────────────────────────
    private WaveConfig GetWaveConfig(int waveNumber)
    {
        WaveConfig config = waveConfigs.Find(w => w.waveNumber == waveNumber);

        // 해당 웨이브 없으면 마지막 구성 기반으로 자동 생성
        if (config.waveNumber == 0 && waveConfigs.Count > 0)
        {
            config = waveConfigs[waveConfigs.Count - 1];
            config.waveNumber = waveNumber;
            config.steamRaptorCount += waveNumber;
        }

        return config;
    }

    // ─────────────────────────────────────────────
    // 기본 웨이브 구성 자동 생성 (v6: 3지역 구조)
    // 지역 길이가 바뀌어도(테스트 3 / 정식 8) 물량 곡선이 유지되도록
    // "지역 내 진행도 p(0~1)" 기준으로 계산한다.
    // ─────────────────────────────────────────────
    private void GenerateDefaultWaveConfigs(int totalWaves)
    {
        waveConfigs = new List<WaveConfig>();

        for (int i = 1; i <= totalWaves; i++)
        {
            WaveConfig config = new WaveConfig();
            config.waveNumber = i;
            config.spawnInterval = Mathf.Max(0.3f, 1.0f - (i * 0.03f));
            config.difficultyL = GameBalance.EnemyDifficultyL; // 난이도 계수 (GameBalance에서 조정)
            config.hasBoss = GameBalance.IsBossWave(i);        // 각 지역 마지막 + 최종전

            int region = GameBalance.RegionOf(i);
            float p = GameBalance.RegionProgress(i);           // 지역 내 진행도 0~1

            if (region == 1)
            {
                // 지역 1: 구리 사막 - 물리 물량 + 러시. 도구 파괴꾼(전갈)로 정비 압박
                config.steamRaptorCount = 3 + Mathf.RoundToInt(p * 12f);       // 4~15 (6+ 시 무리 러시)
                config.springAnkyloCount = p >= 0.4f ? Mathf.RoundToInt(p * 4f) : 0;
                config.oilCactusCount = p >= 0.6f ? Mathf.RoundToInt(p * 3f) : 0;
                config.scorpionCount = p >= 0.5f ? Mathf.RoundToInt(p * 2f) : 0;
                config.tortoiseCount = p >= 0.85f ? 1 : 0;
            }
            else if (region == 2)
            {
                // 지역 2: 테슬라 협곡 - 전기/독/공중. 조리 방해(프테라)와 원거리전 강제
                config.steamRaptorCount = 4;
                config.boltTeranodonCount = 1 + Mathf.RoundToInt(p * 5f);
                config.poisonPteraCount = p >= 0.3f ? Mathf.RoundToInt(p * 3f) : 0;
                config.overloadFlyCount = p >= 0.5f ? Mathf.RoundToInt(p * 4f) : 0;
                config.magnetParasaurCount = p >= 0.75f ? 1 : 0;
                config.steelRaptorCount = p >= 0.4f ? Mathf.RoundToInt(p * 2f) : 0;
                config.flamePteroCount = p >= 0.6f ? Mathf.RoundToInt(p * 2f) : 0;
            }
            else if (region == 3)
            {
                // 지역 3: 코발트 광산 - 냉기/장갑 정예 + 힐러. 속성 대응과 집중 사격 강제
                config.steamRaptorCount = 3;
                config.boltTeranodonCount = 2;
                config.iceMosaCount = 1 + Mathf.RoundToInt(p * 3f);
                config.crystalPachyCount = p >= 0.35f ? Mathf.RoundToInt(p * 2f) : 0;
                config.magmaCarnoCount = p >= 0.55f ? Mathf.RoundToInt(p * 2f) : 0;
                config.frostMammothCount = p >= 0.85f ? 1 : 0;
                config.steelRaptorCount = 2;
                config.necroSpinoCount = p >= 0.5f ? (p >= 0.9f ? 2 : 1) : 0;
            }
            else
            {
                // 최종전: 정예 호위 소수 + 최종 보스
                config.iceMosaCount = 2;
                config.magmaCarnoCount = 2;
                config.steelRaptorCount = 2;
                config.necroSpinoCount = 1;
            }

            waveConfigs.Add(config);
        }

        Debug.Log("[WaveManager] " + totalWaves + "웨이브 구성 생성 완료 (지역 길이 "
            + GameBalance.RegionLength + ", 보스 " + GameBalance.RegionLength + "/"
